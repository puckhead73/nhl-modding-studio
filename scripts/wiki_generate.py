"""Render the generated wiki pages from the audit data under ``docs/audits/data``.

Generated pages (all under ``wiki/``, each starting with ``BANNER``):

* ``Schema-<Title>-<Platform>.md`` — one per reference database snapshot in
  ``docs/audits/data/schema/*.json``: the table list with record counts and, per
  table, a collapsed field list (name, id, width, range, key, foreign key).
* ``Schema-Index.md`` — the list of those pages with table and field totals.
* ``Save-Formats-by-Title.md`` — ``save-matrix.csv``: every committed save fixture
  with its content-detected type, codec and round-trip status.
* ``Surface-Capabilities-by-Title.md`` — ``surface-capabilities.csv``: which
  editing surfaces each title's database supports.

Modes (one is required; the script never writes without ``--write``):

    python scripts/wiki_generate.py --check   # render to memory, compare, report drift; exit 1 on drift
    python scripts/wiki_generate.py --write   # install the rendered pages; remove obsolete generated pages

Only files that begin with ``BANNER`` are generator-owned; a hand-written page
that occupies a generated name makes ``--write`` refuse before touching anything.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import OrderedDict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATA = REPO_ROOT / "docs" / "audits" / "data"
DEFAULT_WIKI = REPO_ROOT / "wiki"

BANNER = "<!-- generated by scripts/wiki_generate.py from docs/audits/data; do not edit by hand -->"
# Bumped by hand whenever the pages are regenerated against newer audit data.
REVIEW_DATE = "2026-10-20"

GAME_LABEL = {
    "nhl07": "NHL 07", "nhl08": "NHL 08", "nhl09": "NHL 09", "nhl10": "NHL 10", "nhl11": "NHL 11",
    "nhl12": "NHL 12", "nhl13": "NHL 13", "nhl14": "NHL 14", "nhl15": "NHL 15", "nhl16": "NHL 16",
    "nhl17": "NHL 17", "nhl18": "NHL 18", "nhl19": "NHL 19", "nhl20": "NHL 20", "nhl21": "NHL 21",
    "nhllegacy": "NHL Legacy",
}
PLATFORM_LABEL = {"ps3": "PS3", "xbox360": "Xbox 360", "xbox": "Xbox 360", "ps4": "PS4", "recomp": "Legacy Recompiled"}
GAME_ORDER = list(GAME_LABEL)
PLATFORM_ORDER = ["xbox360", "ps3", "ps4"]


def game_label(game: str) -> str:
    return GAME_LABEL.get(game, game.upper())


def platform_label(platform: str) -> str:
    return PLATFORM_LABEL.get(platform, platform)


def page_name(game: str, platform: str) -> str:
    return "Schema-" + game_label(game).replace(" ", "-") + "-" + platform_label(platform).replace(" ", "-")


def sort_key(game: str, platform: str) -> tuple[int, int]:
    g = GAME_ORDER.index(game) if game in GAME_ORDER else len(GAME_ORDER)
    p = PLATFORM_ORDER.index(platform) if platform in PLATFORM_ORDER else len(PLATFORM_ORDER)
    return (g, p)


def md_cell(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ")


def fmt_int(value) -> str:
    try:
        return f"{int(value):,}".replace(",", " ")
    except (TypeError, ValueError):
        return md_cell(value)


# --- schema pages -------------------------------------------------------------------------------

def render_schema(snapshot: dict) -> str:
    game, platform = snapshot["game"], snapshot["platform"]
    title = f"Schema: {game_label(game)} ({platform_label(platform)})"
    tables = sorted(snapshot["tables"], key=lambda t: t["name"])
    lines = [BANNER, f"# {title}", ""]
    lines.append(
        f"**Evidence:** measured: generated from the project's schema snapshot of this title's reference "
        f"database (`{snapshot['db']}`), itself derived from the shipped file and its metadata. "
        "Record counts are the shipped population and allocation; see [Roster Model](Roster-Model) for the ceilings."
    )
    lines.append("")
    meta = "yes (`" + snapshot["meta_file"] + "`)" if snapshot.get("meta_present") else "no (names borrowed by id)"
    lines += [
        "| Fact | Value |", "|---|---|",
        f"| Database | `{snapshot['db']}` |",
        f"| Generation | {md_cell(snapshot.get('generation'))} |",
        f"| Byte order | {md_cell(snapshot.get('endian'))}-endian |",
        f"| TDB version | {md_cell(snapshot.get('tdb_version'))} |",
        f"| Metadata file shipped | {meta} |",
        f"| Tables | {fmt_int(snapshot.get('table_count', len(tables)))} |",
        f"| Fields | {fmt_int(snapshot.get('field_total'))} |",
        "",
        "Ids are shown in the real (community) spelling first and the raw on-disk spelling second where they differ; "
        "see [TDB Id Reversal and Naming](TDB-Id-Reversal-and-Naming). Widths are bits; ranges are the declared "
        "`rangelow..rangehigh`; **key** marks primary-key fields; **fk** names the parent table of a declared foreign key.",
        "",
        "## Tables",
        "",
        "| Table | Id | Records (populated / allocated) | Record bytes | Fields |",
        "|---|---|---|---|---|",
    ]
    for t in tables:
        ident = t["canonical_id"] if t["canonical_id"] == t["raw_id"] else f"{t['canonical_id']} (raw {t['raw_id']})"
        lines.append(
            f"| [{md_cell(t['name'])}](#{anchor(t['name'])}) | `{ident}` | {fmt_int(t['current_records'])} / "
            f"{fmt_int(t['max_records'])} | {fmt_int(t['record_len_bytes'])} | {fmt_int(t['field_count'])} |"
        )
    lines += ["", "## Fields by table", ""]
    for t in tables:
        lines.append(f"### {md_cell(t['name'])}")
        lines.append("")
        lines.append("<details><summary>" + f"{fmt_int(t['field_count'])} fields · `{t['canonical_id']}`" + "</summary>")
        lines.append("")
        lines.append("| Field | Id | Bits | Range | Flags |")
        lines.append("|---|---|---|---|---|")
        for f in sorted(t["fields"], key=lambda f: f.get("bit_offset", 0)):
            flags = []
            if f.get("key"):
                flags.append("key")
            if f.get("fk_parent"):
                flags.append("fk " + str(f["fk_parent"]))
            if f.get("updatable") is False:
                flags.append("not updated by the game")
            if f.get("meta_type") and f["meta_type"] != "integer":
                flags.append(str(f["meta_type"]))
            rng = "" if f.get("range_low") is None else f"{f['range_low']}..{f['range_high']}"
            ident = f["canonical_id"] if f["canonical_id"] == f["raw_id"] else f"{f['canonical_id']} ({f['raw_id']})"
            lines.append(f"| {md_cell(f['name'])} | `{ident}` | {f['bit_width']} | {rng} | {md_cell(', '.join(flags))} |")
        lines += ["", "</details>", ""]
    lines += [f"Last reviewed: {REVIEW_DATE}", ""]
    return "\n".join(lines)


def anchor(heading: str) -> str:
    out = []
    for ch in heading.lower():
        if ch.isalnum():
            out.append(ch)
        elif ch in " -":
            out.append("-")
    return "".join(out)


def render_schema_index(snapshots: list[dict]) -> str:
    lines = [BANNER, "# Schema Index", "",
             "**Evidence:** measured: one page per reference database snapshot, generated from the audit data.", "",
             "Each page lists every table of that title's main database with its record counts and fields. "
             "For what changes between titles see [Schema Drift Across Titles](Schema-Drift-Across-Titles).", "",
             "| Title | Platform | Database | Tables | Fields | Metadata shipped |", "|---|---|---|---|---|---|"]
    for s in sorted(snapshots, key=lambda s: sort_key(s["game"], s["platform"])):
        lines.append(
            f"| [{game_label(s['game'])}]({page_name(s['game'], s['platform'])}) | {platform_label(s['platform'])} | "
            f"`{s['db']}` | {fmt_int(s.get('table_count'))} | {fmt_int(s.get('field_total'))} | "
            f"{'yes' if s.get('meta_present') else 'no'} |"
        )
    lines += ["", "NHL 07 on PS3 is a research copy of the Xbox 360 release, not a shipping target.", "",
              f"Last reviewed: {REVIEW_DATE}", ""]
    return "\n".join(lines)


# --- save formats ---------------------------------------------------------------------------------

STATUS_WORDS = {
    "edit-roundtrip": "edit round trip proven",
    "experimental-roundtrip": "round trip proven, write experimental",
    "roundtrip": "codec round trip only (not a roster target)",
    "read-only": "read-only",
}


def render_save_formats(rows: list[dict]) -> str:
    lines = [BANNER, "# Save Formats by Title", "",
             "**Evidence:** measured: generated from the save-container matrix, where every committed save "
             "fixture is classified from its bytes and round-tripped. Nothing here is game-verified.", "",
             "Each row is one sample save. *Detected type* comes from the file's own content, never its folder name; "
             "*codec* is the container variant; *inner TDB* says whether a coherent database was found; *edit* whether a "
             "real field edit went through the editor and survived a reopen. See "
             "[Save Containers for Xbox 360 and PS3](Save-Containers-Xbox-360-and-PS3) and "
             "[Save Containers for PS4](Save-Containers-PS4).", ""]
    grouped: OrderedDict[tuple[str, str], list[dict]] = OrderedDict()
    for r in sorted(rows, key=lambda r: (sort_key(r["game"], r["platform"]), r["slot"])):
        grouped.setdefault((r["game"], r["platform"]), []).append(r)
    for (game, platform), group in grouped.items():
        lines += [f"## {game_label(game)} ({platform_label(platform)})", "",
                  "| Sample | Detected type | Codec | Inner TDB | Edit | Status |", "|---|---|---|---|---|---|"]
        for r in group:
            lines.append(
                f"| {md_cell(r['slot'])} | {md_cell(r['detected_type'])} | {md_cell(r['codec'])} | {md_cell(r['inner_tdb'])} | "
                f"{md_cell(r['semantic_edit'])} | {STATUS_WORDS.get(r['status'], md_cell(r['status']))} |"
            )
        lines.append("")
    lines += [f"Last reviewed: {REVIEW_DATE}", ""]
    return "\n".join(lines)


# --- surface capabilities -------------------------------------------------------------------------

STATE_SYMBOL = {"editable": "edit", "readable": "read", "disabled": "disabled", "unverified": "unverified", "not-applicable": "—"}


def render_surfaces(rows: list[dict]) -> str:
    surfaces = sorted({r["surface"] for r in rows})
    titles = sorted({(r["game"], r["platform"]) for r in rows}, key=lambda gp: sort_key(*gp))
    by_key = {(r["game"], r["platform"], r["surface"]): r for r in rows}
    lines = [BANNER, "# Surface Capabilities by Title", "",
             "**Evidence:** measured: generated from the surface-capability matrix, which probes each reference "
             "database's own tables and descriptors. *edit* = editable, *read* = present but read-only, *disabled* = "
             "present but editing not offered (usually asset authoring), *unverified* = present but meaning unconfirmed, "
             "— = the schema has no such surface. This is what gates the tabs described in [Core Concepts](Core-Concepts).", "",
             "| Title | " + " | ".join(surfaces) + " |", "|---|" + "---|" * len(surfaces)]
    for game, platform in titles:
        cells = [STATE_SYMBOL.get(by_key.get((game, platform, s), {}).get("state", ""), "?") for s in surfaces]
        lines.append(f"| {game_label(game)} ({platform_label(platform)}) | " + " | ".join(cells) + " |")
    reasons = [r for r in rows if r.get("reason")]
    if reasons:
        lines += ["", "## Reasons recorded", "", "<details><summary>" + f"{len(reasons)} entries" + "</summary>", "",
                  "| Title | Surface | State | Reason |", "|---|---|---|---|"]
        for r in sorted(reasons, key=lambda r: (sort_key(r["game"], r["platform"]), r["surface"])):
            lines.append(f"| {game_label(r['game'])} ({platform_label(r['platform'])}) | {r['surface']} | {r['state']} | {md_cell(r['reason'])} |")
        lines += ["", "</details>"]
    lines += ["", f"Last reviewed: {REVIEW_DATE}", ""]
    return "\n".join(lines)


# --- driver --------------------------------------------------------------------------------------

def read_csv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def render_all(data: Path) -> dict[str, str]:
    pages: dict[str, str] = {}
    snapshots = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((data / "schema").glob("*.json"))]
    for s in snapshots:
        pages[page_name(s["game"], s["platform"]) + ".md"] = render_schema(s)
    pages["Schema-Index.md"] = render_schema_index(snapshots)
    pages["Save-Formats-by-Title.md"] = render_save_formats(read_csv(data / "save-matrix.csv"))
    pages["Surface-Capabilities-by-Title.md"] = render_surfaces(read_csv(data / "surface-capabilities.csv"))
    return pages


def owned_pages(wiki: Path) -> dict[str, str]:
    out = {}
    for p in sorted(wiki.glob("*.md")):
        text = p.read_text(encoding="utf-8")
        if text.startswith(BANNER):
            out[p.name] = text
    return out


def normalise(text: str) -> str:
    return text.replace("\r\n", "\n")


def check(data: Path, wiki: Path) -> int:
    rendered = render_all(data)
    owned = owned_pages(wiki)
    missing = sorted(n for n in rendered if not (wiki / n).exists())
    foreign = sorted(n for n in rendered if (wiki / n).exists() and n not in owned)
    changed = sorted(n for n in rendered if n in owned and normalise(owned[n]) != normalise(rendered[n]))
    obsolete = sorted(n for n in owned if n not in rendered)
    for label, names in (("missing", missing), ("occupied by a hand-written page", foreign), ("changed", changed), ("obsolete", obsolete)):
        for n in names:
            print(f"{label}: {n}")
    drift = missing or foreign or changed or obsolete
    print(f"wiki_generate --check: {len(rendered)} pages rendered, {'drift found' if drift else 'no drift'}")
    return 1 if drift else 0


def write(data: Path, wiki: Path) -> int:
    rendered = render_all(data)
    owned = owned_pages(wiki)
    foreign = sorted(n for n in rendered if (wiki / n).exists() and n not in owned)
    if foreign:
        for n in foreign:
            print(f"refused: {n} exists and is not generator-owned (no banner)")
        return 2
    wiki.mkdir(parents=True, exist_ok=True)
    written = 0
    for n, text in rendered.items():
        if normalise(owned.get(n, "")) != normalise(text):
            (wiki / n).write_text(text, encoding="utf-8", newline="\n")
            written += 1
    removed = 0
    for n in sorted(owned):
        if n not in rendered:
            (wiki / n).unlink()
            removed += 1
    print(f"wiki_generate --write: {len(rendered)} pages rendered, {written} written, {removed} obsolete removed")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="compare the rendered pages with wiki/ and report drift")
    mode.add_argument("--write", action="store_true", help="install the rendered pages into wiki/")
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA, help="audit data folder (default: docs/audits/data)")
    parser.add_argument("--wiki", type=Path, default=DEFAULT_WIKI, help="wiki source folder (default: wiki/)")
    args = parser.parse_args(argv)
    return check(args.data, args.wiki) if args.check else write(args.data, args.wiki)


if __name__ == "__main__":
    sys.exit(main())
