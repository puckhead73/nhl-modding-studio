const LEAGUE_KEYS: [&str; 14] = [
    "NHL", "AHL", "ECHL", "OHL", "QMJHL", "WHL", "SMLIIGA", "elitserien", "Allsvenskan", "TournamentFile",
    "TXT_TOURNAMENT", "CUSTOM_TEAMS", "TXT_CHAMPIONS_LEAGUE", "TXT_SPENGLER_CUP",
];

fn kind_from_key(key: &str) -> Result<&'static str, String> {
    if LEAGUE_KEYS.contains(&key) || key.starts_with("TXT_LEAGUE_") {
        Ok("league")
    } else if key.ends_with("Conference") || key.starts_with("Conference") {
        Ok("conference")
    } else if key.ends_with("Division") || key.starts_with("Division") {
        Ok("division")
    } else if key.starts_with("Pool") || key.starts_with("TXT_GROUP_") || key.ends_with("_POOL") {
        Ok("pool")
    } else if key == "Playoffs" {
        Ok("tournament")
    } else {
        Err(format!("unclassified key {key}"))
    }
}

/// The key family of a lettered sub-group (`PoolA` -> `Pool`, `TXT_GROUP_A` -> `TXT_GROUP`): the
/// trailing `_X` or `X` (one capital) removed, as the research bake did.
fn family(k: &str) -> String {
    let b = k.as_bytes();
    if b.len() >= 2 && b[b.len() - 2] == b'_' && b[b.len() - 1].is_ascii_uppercase() {
        k[..k.len() - 2].to_string()
    } else if !b.is_empty() && b[b.len() - 1].is_ascii_uppercase() {
        k[..k.len() - 1].to_string()
    } else {
        k.to_string()
    }
}

struct Row {
    id: u64,
    key: String,
    kind: &'static str,
    leagues: Vec<u64>,
    cur_head: Option<u64>,
    used: bool,
    logo_index: Option<u64>,
    text: String,
    evidence: &'static str,
    note: Option<String>,
    hypothesis: Option<String>,
}

fn render_ps4(ctx: &Ctx, json: &Value, vocabs: &LeagueVocabularies, game: &str) -> Result<Rendered, String> {
    let t = &json["titles"][game];
    let Some(w) = ps4_witness(ctx, game)? else {
        return Ok(Rendered::Skipped(format!(
            "{game}: the witness database is the real CUSA15439 nhl_game.db (private fixture); pass --fixtures <root> to render and verify it"
        )));
    };
    let db = TdbFile::parse(&w.bytes).map_err(|e| format!("{game}: {e}"))?;
    let witness = &t["witness"];
    let wdb = witness["db"]["sha256"].as_str().unwrap_or("");
    if wdb != w.sha256 {
        return Err(format!("{game}: the witness database on disk ({}) is not the research witness ({wdb})", w.sha256));
    }
    let cat = LeagueCatalog::build(&db, &w.meta, vocabs, Some(game));
    let league_key = |code: u64| cat.league(code).and_then(|l| l.name_key.clone()).unwrap_or_else(|| "?".into());

    // Usage per league (the research JSON's marginals, measured on the same witness).
    let usage = t["team_table_groups_by_league"].as_object().ok_or("usage")?;
    let mut head_leagues: BTreeMap<u64, BTreeSet<u64>> = BTreeMap::new();
    let mut conf_use: BTreeMap<u64, BTreeSet<u64>> = BTreeMap::new();
    let mut div_use: BTreeMap<u64, BTreeSet<u64>> = BTreeMap::new();
    let mut head_votes: BTreeMap<u64, BTreeMap<u64, u64>> = BTreeMap::new();
    for (lc, u) in usage {
        let lc: u64 = lc.parse().map_err(|_| "league code")?;
        let heads: Vec<u64> = u["leaguegroup"].as_object().ok_or("lg")?.keys().map(|k| k.parse().unwrap()).collect();
        let [head] = heads[..] else { return Err(format!("{game}: league {lc} has several league groups")) };
        head_leagues.entry(head).or_default().insert(lc);
        for (slot, acc) in [("conferencegroup", &mut conf_use), ("divisiongroup", &mut div_use)] {
            for (gid, n) in u[slot].as_object().ok_or(slot)? {
                let gid: u64 = gid.parse().unwrap();
                acc.entry(gid).or_default().insert(lc);
                *head_votes.entry(gid).or_default().entry(head).or_default() += n.as_u64().unwrap_or(0);
            }
        }
    }
    let majority_head = |gid: u64| -> u64 {
        let v = &head_votes[&gid];
        *v.iter().max_by_key(|(h, n)| (**n, std::cmp::Reverse(**h))).map(|(h, _)| h).unwrap()
    };

    // Rows: kind and block, as the research JSON lists the ids.
    let groups = t["groups"].as_array().ok_or("groups")?;
    let mut rows: Vec<Row> = Vec::new();
    let mut cur_head: Option<u64> = None;
    for g in groups {
        let gid = g["group_id"].as_u64().ok_or("group_id")?;
        let key = g["key"].as_str().unwrap_or("").to_string();
        let kind: &'static str = if head_leagues.contains_key(&gid) {
            cur_head = Some(gid);
            "league"
        } else if gid == 0 {
            cur_head = None;
            "unused"
        } else if (2..=5).contains(&gid) && key == "NHL" {
            "unused"
        } else if conf_use.contains_key(&gid) && div_use.contains_key(&gid) {
            if key.ends_with("Conference") { "conference" } else { "pool" }
        } else if conf_use.contains_key(&gid) {
            "conference"
        } else if div_use.contains_key(&gid) {
            "division"
        } else if key.is_empty() {
            "unused"
        } else {
            let k = kind_from_key(&key)?;
            if k == "league" {
                cur_head = Some(gid);
            }
            k
        };
        let leagues: Option<Vec<u64>> = if kind == "unused" {
            Some(Vec::new())
        } else if kind == "league" {
            Some(head_leagues.get(&gid).map(|s| s.iter().copied().collect()).unwrap_or_default())
        } else if head_votes.contains_key(&gid) {
            Some(head_leagues[&majority_head(gid)].iter().copied().collect())
        } else {
            None
        };
        let ev = g["evidence"].as_str().unwrap_or("");
        let (evidence, note): (&'static str, Option<String>) = if ev.starts_with("array order") {
            ("traced-static", None)
        } else if ev.starts_with("inferred") {
            ("inferred", Some(ev.to_string()))
        } else if ev.starts_with("unknown") {
            let keys: Vec<String> = head_leagues
                .get(&gid)
                .map(|s| s.iter().map(|&lc| format!("{lc} = {}", league_key(lc))).collect())
                .unwrap_or_default();
            ("unknown", Some(format!("{ev} | stockleagues keys of the leagues carrying it on this witness database: {}", keys.join(", "))))
        } else if ev.starts_with("NHL 18 array carries five NHL") {
            ("traced-static", if gid != 1 { Some(ev.to_string()) } else { None })
        } else if ev.starts_with("unused by the team table") {
            ("traced-static", Some("id 0 is never carried by a team row".to_string()))
        } else {
            return Err(format!("{game}: unclassified evidence {ev:?}"));
        };
        rows.push(Row {
            id: gid,
            key,
            kind,
            leagues: leagues.unwrap_or_default(),
            cur_head,
            used: head_leagues.contains_key(&gid) || conf_use.contains_key(&gid) || div_use.contains_key(&gid),
            logo_index: g["art_id"].as_u64(),
            text: g["text"].as_str().unwrap_or("").to_string(),
            evidence,
            note,
            hypothesis: g["candidate_label_hypothesis"].as_str().map(|x| x.to_string()),
        });
        // Mark rows whose block is still to be resolved (unused sub-groups).
        if kind != "unused" && kind != "league" && !head_votes.contains_key(&gid) {
            rows.last_mut().unwrap().leagues = vec![u64::MAX];
        }
    }
    // Unused sub-groups: a pool whose key family has a used sibling joins that sibling's block;
    // otherwise the preceding head's block when that head demonstrably has sub-groups (used
    // ones, or a tournament head whose pools/conferences/divisions are its own file); otherwise
    // no established parent.
    let resolved: Vec<Vec<u64>> = rows
        .iter()
        .map(|r| {
            if r.leagues != [u64::MAX] {
                return r.leagues.clone();
            }
            let sib = rows.iter().find(|x| {
                x.leagues != [u64::MAX] && !x.leagues.is_empty() && x.kind == r.kind && family(&x.key) == family(&r.key) && x.id.abs_diff(r.id) <= 12
            });
            if let Some(x) = sib {
                return x.leagues.clone();
            }
            if let Some(h) = r.cur_head {
                if let Some(hl) = head_leagues.get(&h) {
                    let hl: Vec<u64> = hl.iter().copied().collect();
                    let head_key = rows.iter().find(|x| x.id == h).map(|x| x.key.as_str()).unwrap_or("");
                    let has_sub = rows.iter().any(|x| x.kind != "league" && head_votes.contains_key(&x.id) && x.leagues == hl);
                    if has_sub || ["TournamentFile", "TXT_TOURNAMENT", "TXT_SPENGLER_CUP"].contains(&head_key) {
                        return hl;
                    }
                }
            }
            Vec::new()
        })
        .collect();
    for (r, l) in rows.iter_mut().zip(resolved) {
        r.leagues = l;
    }

    // The witnessed structure, derived by the same code the runtime uses.
    let defs: Vec<GroupDef> = rows
        .iter()
        .map(|r| GroupDef {
            id: r.id,
            key: r.key.clone(),
            kind: r.kind.to_string(),
            league_code: r.leagues.first().map(|&x| x as i64).unwrap_or(-1),
            leagues: Some(r.leagues.iter().map(|&x| x as i64).collect()),
            logo_index: r.logo_index.unwrap_or(0),
            text: r.text.clone(),
            used: r.used,
            evidence: Some(r.evidence.to_string()),
            note: r.note.clone(),
            hypothesis_key: r.hypothesis.clone(),
        })
        .collect();
    let fields = GroupFields { league: "iIBl".into(), conference: "OwTu".into(), division: "CGMK".into() };
    let pairs = witness_pairs(&db, &fields, &defs).ok_or_else(|| format!("{game}: team table lacks the group fields"))?;
    let signature = Signature::of(&db).ok_or_else(|| format!("{game}: no team table"))?;

    // Render.
    let cusa = witness["cusa"].as_str().unwrap_or("");
    let n = &game[3..];
    let va = t["table_va"].as_str().unwrap_or("");
    let stride = t["stride"].as_u64().unwrap_or(0);
    let mut o = String::new();
    o.push_str(&format!("# Competition groups for NHL {n} on PS4 ({cusa}): the table the executable indexes with the\n"));
    o.push_str("# team row's global group ids `leaguegroup` (iIBl), `conferencegroup` (OwTu) and `divisiongroup` (CGMK).\n");
    o.push_str("# Generated by `cargo run -p studio-api --bin competition-groups -- --write` (P1-C, 2026-09-18) from research\n");
    o.push_str("# handoff P1.2-PS4 (docs/research/overnight-2026-09-18/17-ps4-groups-and-consumer-leads.md;\n");
    o.push_str("# data/ps4-competition-groups.json): a pointer array of dictionary keys read from this install's own eboot.bin\n");
    o.push_str(&format!("# at VA {va} (stride {stride}; id 1 = NHL, id k >= 6 = entry k-6 from `WesternConference`), cross-checked against\n"));
    o.push_str("# the same install's base nhl_game.db. Per-row `evidence` is the research's key-lookup class: traced-static\n");
    o.push_str("# (array order == DB usage) / inferred (usage-only; array order disagrees or lacks the id) / unknown (no key\n");
    o.push_str("# found; `hypothesis_key` is a hint, never the name). `kind` / `leagues` are INFERRED from how the witness\n");
    o.push_str("# team table uses each id (a league group heads a block; a used sub-group belongs to the head the majority of\n");
    o.push_str("# its rows carry; an unused sub-group joins a used sibling of its key family or a tournament head; otherwise it\n");
    o.push_str("# has no established parent). Ids are TITLE-SPECIFIC. Labels resolve through the title's own dictionary\n");
    o.push_str("# (the `key`) when one is attached; `text` is the English text observed. The witnessed structure section at the\n");
    o.push_str("# end (signature, known databases, conference/division pairs per block) is measured on the witness database.\n");
    o.push_str(&format!("game = {}\napplies_to = [{}]\nplatforms = [\"ps4\"]\nsource = \"stockleagues\"\n\n", s(game), s(game)));
    o.push_str("[fields]\nleague = \"iIBl\"\nconference = \"OwTu\"\ndivision = \"CGMK\"\n\n");
    o.push_str("[witness]\n");
    o.push_str(&format!("game = {}\nplatform = \"ps4\"\n", s(game)));
    let from = witness["db"]["from"].as_str().unwrap_or("");
    let mut src = format!("{cusa} eboot.bin group table at VA {va} (P1.2-PS4, ps4_group_table.py); base nhl_game.db from {from}");
    let patches: Vec<&str> = witness["patched_db_members_present"].as_array().map(|a| a.iter().filter_map(|x| x.as_str()).collect()).unwrap_or_default();
    if !patches.is_empty() {
        src.push_str(&format!("; patch DB members present: {}", patches.join(", ")));
    }
    o.push_str(&format!("source = {}\n", s(&src)));
    o.push_str(&format!("cusa = {}\n", s(cusa)));
    o.push_str(&format!("executable_sha256 = {}\n", s(witness["eboot_sha256"].as_str().unwrap_or(""))));
    o.push_str(&format!("database_sha256 = {}\n", s(wdb)));
    if let Some(d) = witness["dictionary"]["sha256"].as_str() {
        o.push_str(&format!("dictionary_sha256 = {}\n", s(d)));
    }
    let vers: Vec<String> = witness["param_sfo_versions"].as_array().map(|a| a.iter().filter_map(|x| x.as_str()).map(|x| s(x.trim_end_matches('\0'))).collect()).unwrap_or_default();
    o.push_str(&format!("param_sfo_versions = [{}]\n", vers.join(", ")));
    let mut notes: Vec<String> = witness_notes(game).iter().map(|x| x.to_string()).collect();
    // The keys of every league sharing a block, as this witness database keys them (the research
    // wording is not authority over the database).
    for r in rows.iter().filter(|r| r.kind == "league" && r.leagues.len() > 1) {
        notes.push(format!(
            "block {} ({}) is shared by stockleagues rows {}",
            r.id,
            if r.key.is_empty() { "unnamed" } else { &r.key },
            r.leagues.iter().map(|&lc| format!("{lc} = {}", league_key(lc))).collect::<Vec<_>>().join(", ")
        ));
    }
    o.push_str(&format!("notes = [{}]\n\n", notes.iter().map(|x| s(x)).collect::<Vec<_>>().join(", ")));
    for r in &rows {
        o.push_str("[[groups]]\n");
        o.push_str(&format!("id = {}\nkey = {}\nkind = {}\n", r.id, s(&r.key), s(r.kind)));
        o.push_str(&format!("league_code = {}\nleagues = {}\n", r.leagues.first().map(|x| x.to_string()).unwrap_or("-1".into()), list(&r.leagues)));
        if let Some(l) = r.logo_index {
            o.push_str(&format!("logo_index = {l}\n"));
        }
        o.push_str(&format!("text = {}\nused = {}\nevidence = {}\n", s(&r.text), r.used, s(r.evidence)));
        if let Some(n) = &r.note {
            o.push_str(&format!("note = {}\n", s(n)));
        }
        if let Some(h) = &r.hypothesis {
            o.push_str(&format!("hypothesis_key = {}\n", s(h)));
        }
    }
    o.push('\n');
    o.push_str(&render_structure(&w, &signature, &pairs, game, &format!("{cusa} base nhl_game.db ({from})")));
    Ok(Rendered::Text(o))
}

fn render_structure(w: &Witness, signature: &Signature, pairs: &[PairDef], game: &str, base_source: &str) -> String {
    let mut o = String::new();
    o.push_str(MARKER);
    o.push('\n');
    o.push_str("# Measured on the witness database named below. `[[pairs]]` are the (conference, division) arrangements its\n");
    o.push_str("# stock rows carry per league block (`head` = the rows' leaguegroup); `regular` pairs are the choosable ones,\n");
    o.push_str("# `exceptional` pairs are recorded with their rows and never offered. The signature identifies the title's\n");
    o.push_str("# database structure independently of edits (table set, capacities); the known databases are recorded identities.\n");
    o.push_str("[signature]\n");
    o.push_str(&format!("tables = {}\ntable_set_sha256 = {}\nteam_max_records = {}\n", signature.tables, s(&signature.table_set_sha256), signature.team_max_records));
    if let Some(n) = signature.stockleagues_max_records {
        o.push_str(&format!("stockleagues_max_records = {n}\n"));
    }
    o.push('\n');
    o.push_str(&format!("[[known_databases]]\nrole = \"base\"\nsha256 = {}\nsource = {}\n", s(&w.sha256), s(base_source)));
    for (role, sha, source) in known_databases(game) {
        o.push_str(&format!("[[known_databases]]\nrole = {}\nsha256 = {}\nsource = {}\n", s(role), s(sha), s(source)));
    }
    o.push('\n');
    for p in pairs {
        o.push_str("[[pairs]]\n");
        o.push_str(&format!("head = {}\nconference = {}\ndivision = {}\nrows = {}\narrangement = {}\nleagues = {}\n", p.head, p.conference, p.division, p.rows, s(&p.arrangement), list(&p.leagues)));
        if !p.teams.is_empty() {
            o.push_str(&format!("teams = {}\n", list(&p.teams)));
        }
        if let Some(n) = &p.note {
            o.push_str(&format!("note = {}\n", s(n)));
        }
    }
    o
}

// ---------------------------------------------------------------------------------------------
// gen7: append the witnessed structure to the maintained file
// ---------------------------------------------------------------------------------------------

fn render_gen7(ctx: &Ctx, dir: &Path, game: &str) -> Result<Rendered, String> {
    let path = dir.join(format!("{game}.toml"));
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?.replace("\r\n", "\n");
    let head = match text.find(MARKER) {
        Some(i) => text[..i].trim_end_matches('\n').to_string() + "\n\n",
        None => text.trim_end_matches('\n').to_string() + "\n\n",
    };
    let table = GroupTable::from_toml(&head).map_err(|e| format!("{game}: {e}"))?;
    let d = ctx.repo.join(format!("anchors/xbox360/{game}/databases"));
    let w = load_witness(&d.join("nhlng.db"), &d.join("nhlng-meta.xml"))?;
    let db = TdbFile::parse(&w.bytes).map_err(|e| format!("{game}: {e}"))?;
    let pairs = witness_pairs(&db, &table.fields, &table.groups).ok_or_else(|| format!("{game}: team table lacks the group fields"))?;
    let signature = Signature::of(&db).ok_or_else(|| format!("{game}: no team table"))?;
    let mut o = head;
    o.push_str(&render_structure(
        &w,
        &signature,
        &pairs,
        game,
        &format!("anchors/xbox360/{game}/databases/nhlng.db (Xbox 360 anchor; the PS3 anchor of this title is byte-identical)"),
    ));
    Ok(Rendered::Text(o))
}
