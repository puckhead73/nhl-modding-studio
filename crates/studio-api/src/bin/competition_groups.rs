//! `competition-groups` — the reproducible source of `defs/leagues/groups/*.toml` (P1-C-R1).
//!
//! Inputs (all repository-relative unless `--fixtures` is given):
//!
//! * PS4 NHL 15–21: research handoff 17's executable walk
//!   `docs/research/overnight-2026-09-18/data/ps4-competition-groups.json` (the key lookup per
//!   id and its evidence class) and each title's witness database
//!   `anchors/ps4/<game>/databases/nhl_game.db` (+ `-meta.xml`). NHL 20's witness is the real
//!   CUSA15439 database, which is not committed (the repository anchor is an NHL 19 base copy):
//!   it is read from `<fixtures>/databases/nhl20-ps4-cusa15439/inxp_00.big/` when `--fixtures`
//!   is given and reported as *not verifiable* otherwise.
//! * gen7 NHL 12–15 / Legacy: the maintained `defs/leagues/groups/<game>.toml` (everything above
//!   the generated marker is hand-maintained metadata baked by P1.2-X and is never rewritten) and
//!   the Xbox 360 witness `anchors/xbox360/<game>/databases/nhlng.db`.
//!
//! Outputs: for PS4 the whole `ps4-<game>.toml`; for gen7 only the section after the marker
//! line. Both carry the derived **witnessed structure** (`[signature]`, `[[known_databases]]`,
//! `[[pairs]]`) that `studio-domain::competition_groups` consumes; the derivation rules live
//! there (`witness_pairs`) so the runtime and the tool cannot drift apart. Generation decisions
//! (block membership by majority head, sibling inheritance) are inference from database usage
//! and are marked as such in the files; the key lookup evidence comes from the research JSON
//! untouched.
//!
//! Modes: `--check` renders everything to memory and compares byte-for-byte (LF, UTF-8) with the
//! files on disk, printing drift and exiting 1 without writing; `--write` renders everything
//! first and only then replaces each file through a temporary sibling + rename, so a failed
//! transformation never leaves a half-written table. Output is deterministic.
//!
//! ```sh
//! cargo run -p studio-api --bin competition-groups -- --check [--fixtures E:/nhl-studio-fixtures]
//! cargo run -p studio-api --bin competition-groups -- --write [--fixtures E:/nhl-studio-fixtures]
//! ```

