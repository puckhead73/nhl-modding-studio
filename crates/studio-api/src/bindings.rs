/// What [`install`] actually did.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct WriteSummary {
    pub written: Vec<String>,
    pub removed: Vec<String>,
    pub unchanged: usize,
    pub preserved: Vec<String>,
}

/// One planned mutation of the destination.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Action {
    /// The name does not exist yet. Undo = delete.
    Create,
    /// The name exists and is generator-owned. Undo = restore prior bytes.
    Overwrite,
    /// The name is generator-owned but no longer rendered. Undo = restore prior bytes.
    Delete,
}

impl Action {
    fn verb(self) -> &'static str {
        match self {
            Self::Create => "creating",
            Self::Overwrite => "overwriting",
            Self::Delete => "removing",
        }
    }
}

#[derive(Debug, Clone)]
struct PlannedOp {
    name: String,
    action: Action,
}

/// Which half of the installation a hook is being consulted for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Phase {
    Apply,
    Rollback,
}

/// Deterministic fault-injection seam. Production installs use [`NoHook`], which never fails.
/// Deterministic fault-injection seam.
///
/// [`InstallHook::before`] models a rejection that happens **before** the filesystem is touched.
/// [`InstallHook::write_file`] and [`InstallHook::remove_file`] model the operation itself, so a
/// test can mutate the target *partially* and then fail — which is what a real short write, full
/// disk or revoked handle looks like. The distinction matters: a `before` rejection leaves the
/// target untouched, whereas a failing operation may already have damaged it.
///
/// Rollback deliberately uses the real filesystem (gated only by `before`), so a test asserting
/// that prior bytes were restored is asserting about real bytes on disk.
trait InstallHook {
    fn before(&self, phase: Phase, action: Action, name: &str) -> std::io::Result<()> {
        let _ = (phase, action, name);
        Ok(())
    }

    fn write_file(&self, path: &Path, bytes: &[u8]) -> std::io::Result<()> {
        std::fs::write(path, bytes)
    }

    fn remove_file(&self, path: &Path) -> std::io::Result<()> {
        std::fs::remove_file(path)
    }
}

struct NoHook;
impl InstallHook for NoHook {}

/// **Seam 3.** Install an already-rendered `contract` into `live_dir`.
///
/// Everything is rendered, scanned, ownership-checked and preflighted **before** the first
/// destination byte changes. See the module-level "Supported failure guarantees".
pub fn install(contract: &Contract, live_dir: &Path) -> Result<WriteSummary, BindingsError> {
    install_hooked(contract, live_dir, &NoHook, None)
}

/// `install`, with the fault-injection hook and the recovery-material root both injectable.
///
/// `recovery_root` defaults to the system temp directory; tests override it so they can observe
/// exactly the material this call produced, without scanning shared global state.
fn install_hooked(
    contract: &Contract,
    live_dir: &Path,
    hook: &dyn InstallHook,
    recovery_root: Option<&Path>,
) -> Result<WriteSummary, BindingsError> {
    let scan = scan_dir(live_dir)?;

    // --- Validation, all before any mutation ---------------------------------------------------

    // 1. Ownership: a rendered name occupied by a non-generated regular file.
    let ambiguous: Vec<String> = contract
        .keys()
        .filter(|name| {
            scan.files
                .get(*name)
                .is_some_and(|have| !is_generator_owned(have))
        })
        .cloned()
        .collect();
    if !ambiguous.is_empty() {
        return Err(BindingsError::Ownership(ambiguous));
    }

    // 2. Preflight: every path we would write or remove must be a plain regular file (or absent).
    //    Symlinks and other reparse points are rejected, never followed.
    let obsolete: Vec<String> = scan
        .files
        .iter()
        .filter(|(name, have)| !contract.contains_key(*name) && is_generator_owned(have))
        .map(|(name, _)| name.clone())
        .collect();
    let mut issues: Vec<String> = contract
        .keys()
        .chain(obsolete.iter())
        .filter_map(|name| {
            scan.irregular
                .get(name)
                .map(|kind| format!("{name} ({kind})"))
        })
        .collect();
    issues.sort();
    issues.dedup();
    if !issues.is_empty() {
        return Err(BindingsError::Preflight(issues));
    }

    // --- Plan ----------------------------------------------------------------------------------

    let mut summary = WriteSummary::default();
    let mut plan: Vec<PlannedOp> = Vec::new();
    for (name, want) in contract {
        match scan.files.get(name) {
            Some(have) if normalize(have) == normalize(want) => summary.unchanged += 1,
            Some(_) => plan.push(PlannedOp {
                name: name.clone(),
                action: Action::Overwrite,
            }),
            None => plan.push(PlannedOp {
                name: name.clone(),
                action: Action::Create,
            }),
        }
    }
    for name in &obsolete {
        plan.push(PlannedOp {
            name: name.clone(),
            action: Action::Delete,
        });
    }
    summary.preserved = scan
        .files
        .keys()
        .filter(|name| !contract.contains_key(*name) && !obsolete.contains(name))
        .cloned()
        .collect();

    if plan.is_empty() {
        return Ok(summary);
    }

    std::fs::create_dir_all(live_dir).map_err(|e| io_err(live_dir, e))?;

    // --- Recovery material, captured before the first mutation ---------------------------------

    let mut recovery_dir = match recovery_root {
        Some(root) => ScratchDir::new_in(root, "recovery")?,
        None => ScratchDir::new("recovery")?,
    };
    for op in &plan {
        if op.action == Action::Create {
            continue; // nothing to preserve; undo is a delete
        }
        let prior = &scan.files[&op.name];
        let backup = recovery_dir.path().join(&op.name);
        std::fs::write(&backup, prior).map_err(|e| io_err(&backup, e))?;
    }

    // --- Apply ---------------------------------------------------------------------------------

    let mut applied: Vec<&PlannedOp> = Vec::with_capacity(plan.len());
    for op in &plan {
        let path = live_dir.join(&op.name);

        // A `before` rejection means the operation was never attempted, so the target is
        // untouched and only earlier operations need undoing. Once the filesystem operation is
        // entered it may have mutated the target partially — a truncated overwrite, a
        // half-written new file — so the *failing* operation must be recovered too.
        let outcome = match hook.before(Phase::Apply, op.action, &op.name) {
            Err(source) => Err((source, false)),
            Ok(()) => match op.action {
                Action::Create | Action::Overwrite => hook
                    .write_file(&path, &contract[&op.name])
                    .map_err(|e| (e, true)),
                Action::Delete => hook.remove_file(&path).map_err(|e| (e, true)),
            },
        };

        match outcome {
            Ok(()) => {
                applied.push(op);
                match op.action {
                    Action::Create | Action::Overwrite => summary.written.push(op.name.clone()),
                    Action::Delete => summary.removed.push(op.name.clone()),
                }
            }
            Err((source, attempted)) => {
                let mut to_undo = applied.clone();
                if attempted {
                    to_undo.push(op);
                }
                let uncertain = rollback(&to_undo, live_dir, &scan.files, hook);
                let recovery = if uncertain.is_empty() {
                    Recovery::RolledBack
                } else {
                    recovery_dir.keep();
                    Recovery::Failed {
                        recovery_dir: recovery_dir.path().to_path_buf(),
                        uncertain,
                    }
                };
                return Err(BindingsError::Install {
                    file: op.name.clone(),
                    action: op.action.verb(),
                    source,
                    recovery,
                });
            }
        }
    }

    summary.written.sort();
    summary.removed.sort();
    summary.preserved.sort();
    Ok(summary)
}

/// Undo `to_undo` in reverse.
///
/// `to_undo` holds every operation that may have mutated the destination — the ones that
/// succeeded *and*, when the filesystem operation was actually entered, the one that failed. Each
/// undo is written to be correct for a **partially** applied operation as well as a complete one:
///
/// * `Create` — the file did not exist before, so removing it restores membership. A half-written
///   file is removed; a file that was never created at all is already correct, so `NotFound` is
///   success, not a failure.
/// * `Overwrite` and `Delete` — prior bytes were captured before the first mutation, and writing
///   them back is correct whether the target was untouched, truncated, partially rewritten or
///   removed.
///
/// Returns the files whose state could not be restored, with the reason; an empty vector means
/// prior bytes **and** membership are fully restored.
fn rollback(
    to_undo: &[&PlannedOp],
    live_dir: &Path,
    prior: &Contract,
    hook: &dyn InstallHook,
) -> Vec<String> {
    let mut uncertain = Vec::new();
    for op in to_undo.iter().rev() {
        let path = live_dir.join(&op.name);
        let undo = hook
            .before(Phase::Rollback, op.action, &op.name)
            .and_then(|()| match op.action {
                Action::Create => match std::fs::remove_file(&path) {
                    Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
                    other => other,
                },
                Action::Overwrite | Action::Delete => std::fs::write(&path, &prior[&op.name]),
            });
        if let Err(e) = undo {
            uncertain.push(format!("{} ({}): {e}", op.name, op.action.verb()));
        }
    }
    uncertain.sort();
    uncertain
}

