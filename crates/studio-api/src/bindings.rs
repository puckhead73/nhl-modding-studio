    #[test]
    fn error_messages_distinguish_the_failure_classes() {
        let render = BindingsError::Render("boom".into()).to_string();
        let ownership = BindingsError::Ownership(vec!["A.ts".into()]).to_string();
        let preflight = BindingsError::Preflight(vec!["A.ts (directory)".into()]).to_string();
        let rolled_back = BindingsError::Install {
            file: "A.ts".into(),
            action: "creating",
            source: std::io::Error::other("disk"),
            recovery: Recovery::RolledBack,
        }
        .to_string();

        // The three pre-mutation classes may say the destination is untouched...
        for msg in [&render, &ownership, &preflight] {
            assert!(msg.contains("destination not touched"), "{msg}");
        }
        assert!(render.contains("rendering failed"), "{render}");
        assert!(ownership.contains("ownership refusal"), "{ownership}");
        assert!(preflight.contains("preflight rejection"), "{preflight}");

        // ...but an installation failure must never claim it unconditionally.
        assert!(!rolled_back.contains("not touched"), "{rolled_back}");
        assert!(rolled_back.contains("Rollback succeeded"), "{rolled_back}");
    }
