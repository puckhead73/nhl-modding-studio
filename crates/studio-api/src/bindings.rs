/// What happened to the destination after a failed installation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Recovery {
    /// Every applied step was undone. Prior bytes and membership are restored.
    RolledBack,
    /// Rollback itself failed. The recovery directory is **retained**.
    Failed {
        /// Where the prior bytes of every backed-up file still live.
        recovery_dir: PathBuf,
        /// The files whose current on-disk state is uncertain, with the reason.
        uncertain: Vec<String>,
    },
}

#[derive(Debug)]
pub enum BindingsError {
    /// Rendering the DTOs failed. **No destination file was touched.**
    Render(String),
    /// Scanning or reading failed before any mutation. **No destination file was touched.**
    Io {
        path: PathBuf,
        source: std::io::Error,
    },
    /// A live `.ts` file the generator wants to own does not carry the `ts-rs` banner. Ownership
    /// is ambiguous, so installation refuses. **No destination file was touched.**
    Ownership(Vec<String>),
    /// A path the installer would have to write or remove is not a plain regular file — a
    /// directory, a symlink or another reparse point. **No destination file was touched.**
    Preflight(Vec<String>),
    /// Installation failed part-way. Consult [`Recovery`] for the destination's actual state.
    Install {
        /// The file the failing step was acting on.
        file: String,
        /// What the failing step was doing.
        action: &'static str,
        source: std::io::Error,
        recovery: Recovery,
    },
}

impl fmt::Display for BindingsError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Render(msg) => {
                write!(f, "DTO rendering failed: {msg} (destination not touched)")
            }
            Self::Io { path, source } => {
                write!(f, "{}: {source} (destination not touched)", path.display())
            }
            Self::Ownership(paths) => write!(
                f,
                "ownership refusal: {} file(s) in the binding directory occupy a generated name \
                 without the ts-rs banner, so the generator does not own them: {} \
                 (destination not touched)",
                paths.len(),
                paths.join(", ")
            ),
            Self::Preflight(issues) => write!(
                f,
                "preflight rejection: {} path(s) are not plain regular files: {} \
                 (destination not touched)",
                issues.len(),
                issues.join(", ")
            ),
            Self::Install {
                file,
                action,
                source,
                recovery,
            } => match recovery {
                Recovery::RolledBack => write!(
                    f,
                    "installation failed while {action} `{file}`: {source}. Rollback succeeded: \
                     the destination's prior bytes and membership were restored."
                ),
                Recovery::Failed {
                    recovery_dir,
                    uncertain,
                } => write!(
                    f,
                    "installation failed while {action} `{file}`: {source}. \
                     RECOVERY ALSO FAILED — the destination is in an uncertain state. \
                     Uncertain file(s) ({}): {}. Their exact prior bytes are retained at {}. \
                     Copy those files back by hand: a truncated file may have lost its ts-rs \
                     banner, in which case re-running `--write` refuses it as unowned rather \
                     than repairing it.",
                    uncertain.len(),
                    uncertain.join(", "),
                    recovery_dir.display()
                ),
            },
        }
    }
}

impl std::error::Error for BindingsError {}

fn io_err(path: &Path, source: std::io::Error) -> BindingsError {
    BindingsError::Io {
        path: path.to_path_buf(),
        source,
    }
}

