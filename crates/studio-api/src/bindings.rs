// Compare (seam 2) — never mutates
// ---------------------------------------------------------------------------------------------

/// **Seam 2.** Compare an already-rendered `contract` against `live_dir`. **Never writes.**
pub fn compare(contract: &Contract, live_dir: &Path) -> Result<DriftReport, BindingsError> {
    let scan = scan_dir(live_dir)?;

    let mut report = DriftReport {
        rendered: contract.len(),
        ..Default::default()
    };
    for (name, kind) in &scan.irregular {
        report.irregular.push(format!("{name} ({kind})"));
    }
    for (name, want) in contract {
        if scan.irregular.contains_key(name) {
            continue; // already reported as irregular; do not also call it missing
        }
        match scan.files.get(name) {
            None => report.missing.push(name.clone()),
            Some(have) => {
                if !is_generator_owned(have) {
                    report.ambiguous.push(name.clone());
                } else if normalize(have) != normalize(want) {
                    report.changed.push(name.clone());
                }
            }
        }
    }
    for (name, have) in &scan.files {
        if contract.contains_key(name) {
            continue;
        }
        if is_generator_owned(have) {
            report.obsolete.push(name.clone());
        } else {
            report.unowned.push(name.clone());
        }
    }
    // BTreeMap iteration is already sorted; sort explicitly so the contract does not rely on it.
    report.missing.sort();
    report.changed.sort();
    report.obsolete.sort();
    report.ambiguous.sort();
    report.irregular.sort();
    report.unowned.sort();
    Ok(report)
}

