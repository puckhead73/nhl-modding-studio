    /// Fails the Nth matching step, optionally failing rollback steps too.
    struct FailAt {
        phase: Phase,
        after: std::sync::atomic::AtomicUsize,
        fail_rollback_for: Option<Action>,
    }

    impl FailAt {
        /// Fail the apply step that follows `after` successful apply steps.
        fn apply_after(after: usize) -> Self {
            Self {
                phase: Phase::Apply,
                after: std::sync::atomic::AtomicUsize::new(after),
                fail_rollback_for: None,
            }
        }

        /// As above, but every rollback step touching `action` also fails.
        fn with_failing_rollback(mut self, action: Action) -> Self {
            self.fail_rollback_for = Some(action);
            self
        }
    }

    impl InstallHook for FailAt {
        fn before(&self, phase: Phase, action: Action, name: &str) -> std::io::Result<()> {
            if phase == Phase::Rollback {
                return match self.fail_rollback_for {
                    Some(target) if target == action => Err(std::io::Error::new(
                        std::io::ErrorKind::PermissionDenied,
                        format!("injected rollback fault on {name}"),
                    )),
                    _ => Ok(()),
                };
            }
            if phase != self.phase {
                return Ok(());
            }
            let remaining = self.after.load(std::sync::atomic::Ordering::SeqCst);
            if remaining == 0 {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::PermissionDenied,
                    format!("injected apply fault on {name}"),
                ));
            }
            self.after
                .store(remaining - 1, std::sync::atomic::Ordering::SeqCst);
            Ok(())
        }
    }

    /// Models the operation itself failing **after** it has partially mutated its target — a
    /// short write, a full disk, a revoked handle. `target` names the file whose write is
    /// truncated to `keep_bytes` before the error is returned; every other operation is real.
    ///
    /// `failing_rollback` additionally fails the rollback step for that same file, so the
    /// recovery-failure path can be exercised on a genuinely damaged file.
    struct PartialWrite {
        target: &'static str,
        keep_bytes: usize,
        fail_rollback_for_target: bool,
    }

    impl PartialWrite {
        fn new(target: &'static str, keep_bytes: usize) -> Self {
            Self {
                target,
                keep_bytes,
                fail_rollback_for_target: false,
            }
        }

        fn failing_rollback(mut self) -> Self {
            self.fail_rollback_for_target = true;
            self
        }

        fn is_target(&self, path: &Path) -> bool {
            path.file_name().and_then(|n| n.to_str()) == Some(self.target)
        }
    }

    impl InstallHook for PartialWrite {
        fn before(&self, phase: Phase, _action: Action, name: &str) -> std::io::Result<()> {
            if phase == Phase::Rollback && self.fail_rollback_for_target && name == self.target {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::PermissionDenied,
                    format!("injected rollback fault on {name}"),
                ));
            }
            Ok(())
        }

        fn write_file(&self, path: &Path, bytes: &[u8]) -> std::io::Result<()> {
            if !self.is_target(path) {
                return std::fs::write(path, bytes);
            }
            // Truncate-and-partially-write, exactly as a failing real write can leave things.
            std::fs::write(path, &bytes[..self.keep_bytes.min(bytes.len())])?;
            Err(std::io::Error::new(
                std::io::ErrorKind::WriteZero,
                "injected short write",
            ))
        }
    }

