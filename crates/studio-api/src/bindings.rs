/// Render the contract and compare it against `live_dir`. **Nothing is written or repaired.**
pub fn check(live_dir: &Path) -> Result<DriftReport, BindingsError> {
    compare(&render_contract()?, live_dir)
}

/// Render the contract and install it into `live_dir`. The **only** deliberate write path.
pub fn write(live_dir: &Path) -> Result<WriteSummary, BindingsError> {
    write_with(live_dir, render_contract)
}

/// `write`, with the render stage injectable so a rendering failure can be tested deterministically.
fn write_with(
    live_dir: &Path,
    render: impl FnOnce() -> Result<Contract, BindingsError>,
) -> Result<WriteSummary, BindingsError> {
    let contract = render()?;
    install(&contract, live_dir)
}

