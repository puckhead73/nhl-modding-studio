//! The generated TypeScript DTO contract: one authoritative export-root list, an explicit
//! generator, and a deterministic **non-mutating** drift check.
//!
//! Ordinary `cargo test` must never rewrite `app/src/bindings`. The test in this module only
//! *compares*; installation happens exclusively through the `export-bindings` binary:
//!
//! ```text
//! cargo run -p studio-api --bin export-bindings -- --check
//! cargo run -p studio-api --bin export-bindings -- --write
//! ```
//!
//! # Seams
//!
//! The three stages are separated so behaviour can be tested without paying for a real ts-rs
//! render every time:
//!
//! | Stage | Entry point | Notes |
//! |---|---|---|
//! | render | [`render_contract`] | the only stage that runs `ts-rs`; renders into an isolated temp dir |
//! | compare | [`compare`] | pure: a [`Contract`] against a directory scan. Never writes. |
//! | install | [`install`] | the only stage that mutates the destination |
//!
//! [`check`] is render + compare; [`write`] is render + install.
//!
//! # Supported failure guarantees
//!
//! Stated precisely, because the weaker claims matter as much as the stronger ones:
//!
//! * **Rendering failure, ownership refusal and preflight rejection happen before any destination
//!   file is touched.** In those three cases the destination is genuinely unchanged.
//! * **An I/O failure part-way through installation triggers a best-effort rollback** from
//!   recovery material captured before the first mutation. When the rollback succeeds, prior bytes
//!   *and* membership are restored and the recovery directory is discarded. When it does not, the
//!   recovery directory is **retained** and the error names exactly which files are uncertain and
//!   where their prior bytes live.
//! * **No atomicity across a crash or power loss is claimed or provided.** Rollback runs in this
//!   process; if the process dies mid-install, the destination stays as it was at that instant and
//!   the retained recovery directory is the only remedy.
//! * **No protection against a concurrent external writer is claimed or provided.** The
//!   destination is scanned once and acted on; another process writing the same directory
//!   concurrently can invalidate both the plan and the rollback.
//! * **Re-running `--write` does not necessarily repair a damaged tree.** A truncated or partially
//!   rewritten file can have lost its ts-rs banner, at which point it is no longer generator-owned
//!   and a later `--write` correctly *refuses* with an ownership error rather than overwriting it.
//!   When rollback failed, the retained recovery directory is the source of truth: restore the
//!   named files from it by hand, then re-run `--write`.

use std::collections::BTreeMap;
use std::fmt;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

