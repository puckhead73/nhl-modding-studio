/// Normalise for comparison.
///
/// The **only** transformation applied is collapsing CRLF to LF. `ts-rs` always writes LF, but Git
/// is configured with `core.autocrlf=true` in this repository, so a fresh checkout hands us CRLF
/// files that are not substantively different. Nothing else is normalised: trailing whitespace,
/// blank lines, indentation and byte content are all compared as-is, so a real content difference
/// can never be hidden by this step.
fn normalize(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'\r' && bytes.get(i + 1) == Some(&b'\n') {
            out.push(b'\n');
            i += 2;
        } else {
            out.push(bytes[i]);
            i += 1;
        }
    }
    out
}

/// Is this live file one the generator is allowed to own (overwrite / delete)?
fn is_generator_owned(bytes: &[u8]) -> bool {
    String::from_utf8_lossy(bytes).starts_with(TS_RS_BANNER)
}

/// The outcome of a non-mutating comparison between a rendered contract and the live tree.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct DriftReport {
    /// Rendered files with no live counterpart. Sorted.
    pub missing: Vec<String>,
    /// Rendered files whose live counterpart differs after CRLF normalisation. Sorted.
    pub changed: Vec<String>,
    /// Generator-owned live files the current DTO contract no longer produces. Sorted.
    pub obsolete: Vec<String>,
    /// Live files the generator wants to own but which lack the ts-rs banner. Sorted. These are
    /// never written or deleted; they make installation refuse.
    pub ambiguous: Vec<String>,
    /// `.ts` entries that are not plain regular files (directory, symlink, other reparse point),
    /// with the kind appended. Sorted. These block installation and are never followed.
    pub irregular: Vec<String>,
    /// Live files that are neither rendered nor generator-owned. Always preserved; informational.
    pub unowned: Vec<String>,
    /// Number of files the compared contract renders.
    pub rendered: usize,
}

impl DriftReport {
    /// True when the live tree matches the rendered contract in both content and membership.
    pub fn is_clean(&self) -> bool {
        self.missing.is_empty()
            && self.changed.is_empty()
            && self.obsolete.is_empty()
            && self.ambiguous.is_empty()
            && self.irregular.is_empty()
    }
}

impl fmt::Display for DriftReport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        writeln!(f, "{} binding file(s) rendered.", self.rendered)?;
        if self.is_clean() {
            write!(f, "Bindings are in sync.")?;
            return Ok(());
        }
        let mut section = |label: &str, items: &[String]| -> fmt::Result {
            if items.is_empty() {
                return Ok(());
            }
            writeln!(f, "\n{} ({}):", label, items.len())?;
            for item in items {
                writeln!(f, "  {item}")?;
            }
            Ok(())
        };
        section("missing (rendered but absent from the tree)", &self.missing)?;
        section("changed (content differs)", &self.changed)?;
        section(
            "obsolete (generator-owned but no longer rendered)",
            &self.obsolete,
        )?;
        section(
            "ambiguous ownership (present, not ts-rs generated)",
            &self.ambiguous,
        )?;
        section("not a plain regular file (never followed)", &self.irregular)?;
        write!(
            f,
            "\nRun `cargo run -p studio-api --bin export-bindings -- --write` to install the \
             current DTO contract."
        )
    }
}

