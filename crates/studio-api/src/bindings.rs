/// The banner `ts-rs` writes at the top of every file it generates. A `.ts` file in the binding
/// directory is considered **generator-owned** if and only if it starts with this line; anything
/// else is treated as foreign, is never deleted, and is reported separately.
const TS_RS_BANNER: &str =
    "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs).";

/// A rendered binding set: file name → bytes. The binding tree is flat, so a name is a full key.
pub type Contract = BTreeMap<String, Vec<u8>>;

/// The single authoritative export-root list.
///
/// `ts-rs` exports each root together with its whole dependency closure, so this list holds only
/// the roots the command surface actually returns — dependencies come along automatically. It is
/// consumed by *both* the generator and the drift check, so the two can never disagree about what
/// the binding tree is supposed to contain.
macro_rules! export_roots {
    ($($ty:ident),+ $(,)?) => {
        /// Render every root (and its dependency closure) into `out_dir`.
        fn render_roots(out_dir: &Path) -> Result<(), ts_rs::ExportError> {
            $( <crate::dto::$ty as TS>::export_all_to(out_dir)?; )+
            Ok(())
        }

        /// The export roots, in declaration order. Reported by `--check` for traceability.
        pub fn export_root_names() -> Vec<&'static str> {
            vec![ $( stringify!($ty) ),+ ]
        }
    };
}

