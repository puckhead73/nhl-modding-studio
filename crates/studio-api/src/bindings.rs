// Scanning
// ---------------------------------------------------------------------------------------------

/// What a single scan of the destination directory found.
#[derive(Debug, Default)]
struct Scan {
    /// Plain regular `*.ts` files, read into memory.
    files: Contract,
    /// `*.ts` entries that are **not** plain regular files: name → kind. Never read, never
    /// followed, never written.
    irregular: BTreeMap<String, &'static str>,
}

/// Scan every `*.ts` entry directly inside `dir`. A missing directory scans as empty.
///
/// Entry types come from [`std::fs::DirEntry::file_type`], which does **not** traverse symlinks, so
/// a `.ts` symlink is classified as such rather than being followed into another location.
fn scan_dir(dir: &Path) -> Result<Scan, BindingsError> {
    let mut scan = Scan::default();
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(scan),
        Err(e) => return Err(io_err(dir, e)),
    };
    for entry in entries {
        let entry = entry.map_err(|e| io_err(dir, e))?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("ts") {
            continue;
        }
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        let file_type = entry.file_type().map_err(|e| io_err(&path, e))?;
        if file_type.is_symlink() {
            scan.irregular
                .insert(name.to_string(), "symlink/reparse point");
            continue;
        }
        if file_type.is_dir() {
            scan.irregular.insert(name.to_string(), "directory");
            continue;
        }
        if !file_type.is_file() {
            scan.irregular
                .insert(name.to_string(), "not a regular file");
            continue;
        }
        let bytes = std::fs::read(&path).map_err(|e| io_err(&path, e))?;
        scan.files.insert(name.to_string(), bytes);
    }
    Ok(scan)
}

