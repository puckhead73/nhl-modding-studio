/// A uniquely-named temporary directory. Removed on drop unless [`ScratchDir::keep`] is called.
struct ScratchDir {
    path: PathBuf,
    keep: bool,
}

impl ScratchDir {
    fn new(tag: &str) -> Result<Self, BindingsError> {
        Self::new_in(&std::env::temp_dir(), tag)
    }

    /// As [`ScratchDir::new`], but rooted at `root` instead of the system temp directory. Used so
    /// tests can observe recovery material without scanning (and racing on) shared global state.
    fn new_in(root: &Path, tag: &str) -> Result<Self, BindingsError> {
        static SEQ: AtomicU64 = AtomicU64::new(0);
        let nanos = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        let path = root.join(format!(
            "studio-api-bindings-{tag}-{}-{}-{}",
            std::process::id(),
            SEQ.fetch_add(1, Ordering::Relaxed),
            nanos
        ));
        std::fs::create_dir_all(&path).map_err(|e| io_err(&path, e))?;
        Ok(Self { path, keep: false })
    }

    fn path(&self) -> &Path {
        &self.path
    }

    /// Retain the directory past drop — used to preserve recovery material after a failed rollback.
    fn keep(&mut self) {
        self.keep = true;
    }
}

impl Drop for ScratchDir {
    fn drop(&mut self) {
        if !self.keep {
            let _ = std::fs::remove_dir_all(&self.path);
        }
    }
}

/// **Seam 1.** Render the whole contract into a fresh temporary directory and read it back.
///
/// The destination is never involved.
pub fn render_contract() -> Result<Contract, BindingsError> {
    let scratch = ScratchDir::new("render")?;
    render_roots(scratch.path()).map_err(|e| BindingsError::Render(e.to_string()))?;
    Ok(scan_dir(scratch.path())?.files)
}

