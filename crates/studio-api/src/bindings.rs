    /// When recovery of the damaged file itself fails, the damage must be reported — never
    /// reported as a successful restoration — and the true prior bytes must be retained.
    #[test]
    fn failed_recovery_of_a_partially_overwritten_file_is_reported_honestly() {
        let c = tiny();
        let dir = seeded(&c);
        std::fs::write(dir.path().join("Alpha.ts"), owned("stale alpha")).expect("edit");
        std::fs::write(dir.path().join("Beta.ts"), owned("stale beta")).expect("edit");
        let prior_beta = std::fs::read(dir.path().join("Beta.ts")).expect("read");
        let prior_alpha = std::fs::read(dir.path().join("Alpha.ts")).expect("read");
        let recovery_root = ScratchDir::new("test").expect("scratch");

        let err = install_hooked(
            &c,
            dir.path(),
            &PartialWrite::new("Beta.ts", 10).failing_rollback(),
            Some(recovery_root.path()),
        )
        .expect_err("must fail");
        let BindingsError::Install { recovery, .. } = err else {
            panic!("expected an install failure, got {err:?}");
        };
        let Recovery::Failed {
            recovery_dir,
            uncertain,
        } = recovery
        else {
            panic!("a damaged file was reported as fully restored: {recovery:?}");
        };

        // Exactly the damaged file is named, and nothing else.
        assert_eq!(uncertain.len(), 1, "{uncertain:?}");
        assert!(
            uncertain[0].starts_with("Beta.ts (overwriting)"),
            "{uncertain:?}"
        );

        // The damage is real and still present, so the honest report matches reality.
        let damaged = std::fs::read(dir.path().join("Beta.ts")).expect("read");
        assert_eq!(damaged.len(), 10, "fixture assumption: a truncated file");
        assert_ne!(damaged, prior_beta);
        assert!(
            !is_generator_owned(&damaged),
            "fixture assumption: truncation destroyed the ownership banner"
        );

        // The earlier successful operation was still undone.
        assert_eq!(
            std::fs::read(dir.path().join("Alpha.ts")).expect("read"),
            prior_alpha,
            "an earlier operation was left applied"
        );

        // Retained material holds the exact prior bytes of the damaged file.
        assert!(recovery_dir.is_dir(), "recovery material was discarded");
        assert_eq!(
            std::fs::read(recovery_dir.join("Beta.ts")).expect("backup"),
            prior_beta
        );
        assert!(recovery_dir.starts_with(recovery_root.path()));

        // And the documented consequence holds: a later --write refuses rather than repairing.
        let err = install(&c, dir.path()).expect_err("a damaged, unowned file must be refused");
        assert!(
            matches!(err, BindingsError::Ownership(ref v) if v == &vec!["Beta.ts".to_string()]),
            "expected an ownership refusal, got {err:?}"
        );
    }

