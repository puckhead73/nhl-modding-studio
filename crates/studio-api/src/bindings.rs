    #[test]
    fn rollback_failure_retains_recovery_material_and_reports_honestly() {
        let c = synthetic(&[("Alpha.ts", "export type Alpha = 1;")]);
        let dir = ScratchDir::new("test").expect("scratch");
        std::fs::write(dir.path().join("Zulu.ts"), owned("export type Z = 1;")).expect("w");
        std::fs::write(dir.path().join("Yankee.ts"), owned("export type Y = 1;")).expect("w");
        let prior_yankee = std::fs::read(dir.path().join("Yankee.ts")).expect("read");

        // Plan: Create Alpha.ts, Delete Yankee.ts, Delete Zulu.ts. Fail the third apply step, then
        // fail every rollback step that restores a deleted file.
        let recovery_root = ScratchDir::new("test").expect("scratch");
        let err = install_hooked(
            &c,
            dir.path(),
            &FailAt::apply_after(2).with_failing_rollback(Action::Delete),
            Some(recovery_root.path()),
        )
        .expect_err("must fail");
        let BindingsError::Install { recovery, .. } = err else {
            panic!("expected an install failure, got {err:?}");
        };
        let Recovery::Failed {
            recovery_dir,
            uncertain,
        } = recovery
        else {
            panic!("expected recovery to have failed, got {recovery:?}");
        };

        // Honest diagnostics: exactly the file that could not be restored, and nothing else.
        assert_eq!(uncertain.len(), 1, "{uncertain:?}");
        assert!(
            uncertain[0].starts_with("Yankee.ts (removing)"),
            "{uncertain:?}"
        );

        // Recovery material is retained and holds the real prior bytes.
        assert!(recovery_dir.is_dir(), "recovery directory was discarded");
        assert_eq!(
            std::fs::read(recovery_dir.join("Yankee.ts")).expect("backup"),
            prior_yankee,
            "retained backup does not hold the prior bytes"
        );

        // The steps that *could* be undone were: Alpha.ts is gone again.
        assert!(
            !dir.path().join("Alpha.ts").exists(),
            "Create was not undone"
        );
        assert!(!dir.path().join("Yankee.ts").exists(), "fixture assumption");

        // The rendered message names the failure, the recovery failure and the retained location.
        let msg = BindingsError::Install {
            file: "Zulu.ts".into(),
            action: "removing",
            source: std::io::Error::other("x"),
            recovery: Recovery::Failed {
                recovery_dir: recovery_dir.clone(),
                uncertain: uncertain.clone(),
            },
        }
        .to_string();
        assert!(msg.contains("RECOVERY ALSO FAILED"), "{msg}");
        assert!(msg.contains(&recovery_dir.display().to_string()), "{msg}");
        assert!(!msg.contains("not touched"), "misleading claim in: {msg}");

        // The retained material sits under the injected root, so the fixture cleans it up.
        assert!(recovery_dir.starts_with(recovery_root.path()));
    }

