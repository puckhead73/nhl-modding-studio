#[test]
fn both_duplicate_asset_matrices_are_preserved_and_their_differences_published() {
    // Synthetic sources with a **known** disagreement, so the case asserts the behaviour rather
    // than the current contents of a hand-maintained file. The live capability.csv is not read,
    // not copied and not modified by this test.
    let (frozen, candidate, report) = synthetic_frozen_and_migrated("dup");
    assert!(report.divergence_rows > 0, "the two matrices do differ");

    let text = fs::read_to_string(candidate.join("divergence.csv")).expect("divergence");
    let rows = csv::parse(&text).expect("divergence csv");
    let header = rows.first().cloned().unwrap_or_default();
    let at = |name: &str| header.iter().position(|c| c == name).expect(name);
    let (subject, left_src, left_val, right_src, right_val, unresolved) = (
        at("subject"),
        at("left_source"),
        at("left_value"),
        at("right_source"),
        at("right_value"),
        at("unresolved"),
    );

    // 1. The row-missing disagreement survives: `heads` exists on the left only, and the output
    //    says so with both provenances rather than picking a winner.
    let heads = rows
        .iter()
        .skip(1)
        .find(|r| r[subject] == "heads")
        .unwrap_or_else(|| panic!("the left-only `heads` row must be published\n{text}"));
    assert_eq!(heads[left_src], "capability.frozen.csv");
    assert_eq!(heads[right_src], "asset-capability-matrix.frozen.csv");
    assert_eq!(heads[left_val], "present");
    assert_eq!(heads[right_val], "absent");
    assert_eq!(heads[unresolved], "duplicate-source-row-missing");

    // 2. The value disagreement survives with **both** claims intact and attributed.
    let identify = rows
        .iter()
        .skip(1)
        .find(|r| r[subject] == "equipment/identify")
        .unwrap_or_else(|| panic!("the deliberate equipment/identify disagreement\n{text}"));
    assert_eq!(identify[left_val], "partial", "the left claim is preserved");
    assert_eq!(identify[right_val], "pass", "the right claim is preserved");
    assert_eq!(identify[left_src], "capability.frozen.csv");
    assert_eq!(identify[right_src], "asset-capability-matrix.frozen.csv");
    assert_eq!(identify[unresolved], "duplicate-source");

    // 3. Where the two agree, nothing is reported as a difference.
    assert!(
        !rows
            .iter()
            .skip(1)
            .any(|r| r[subject] == "portraits/discover"),
        "agreeing cells must not be published as divergence\n{text}"
    );

    // 4. Neither source is retired: both frozen copies are present and still verify byte-for-byte.
    for (name, _) in migrate::SOURCES {
        assert!(frozen.join(name).is_file(), "{name} retained");
    }
    migrate::verify_freeze(&frozen).expect("both sources still verify");

    // 5. Both sides also survive as layer-L claims, each carrying its own source file and row.
    let root = sandbox("dup-root");
    approve_and_install(&candidate, &root);
    let legacy = store::load_legacy(&root).expect("legacy");
    for source in [
        "capability.frozen.csv",
        "asset-capability-matrix.frozen.csv",
    ] {
        let from_source: Vec<_> = legacy
            .iter()
            .filter(|c| c.source_file == source)
            .filter(|c| c.claim_status_raw == "equipment")
            .collect();
        assert_eq!(
            from_source.len(),
            1,
            "one `equipment` claim from {source}: {:?}",
            legacy.iter().map(|c| &c.claim_id).collect::<Vec<_>>()
        );
        let claim = from_source[0];
        assert!(!claim.source_sha256.is_empty(), "provenance digest");
        assert!(claim.source_row > 0, "provenance row");
        assert!(!claim.qualifies(), "R-LEGACY");
    }
}

