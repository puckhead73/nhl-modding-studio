//! Acceptance cases for migration (S3) —
//! [contract §6, §7.2](../../../docs/plans/qa-evidence-contract.md), cases **A11, A12, A25–A28,
//! A31, A32**.
//!
//! The committed legacy CSVs are **read** here and frozen into an isolated sandbox; nothing under
//! `docs/audits/` is written, and no candidate is installed into the live evidence tree. Migration
//! produces claims, never observations and never manual records.

use std::collections::BTreeSet;
