/// A synthetic recipe registry in the shape `migrate::headmesh_pair_keys` reads.
///
/// Two of the five pairs deliberately share one destination, which is the property R-NO-BACKFILL
/// exists for: a single destination-level row cannot express pair-specific proof. The shared
/// destination is spelled `nhllegacy-xbox360` because `migrate` assigns exactly that target to
/// `capability.frozen.csv` rows; the **pairs, sources and counts are invented**.
fn synthetic_headmesh_registry(dir: &Path) -> PathBuf {
    let path = dir.join("synthetic-headmesh-matrix.toml");
    let text = "\
# SYNTHETIC — built by evidence_migration.rs. Not a copy of any registry and not evidence about
# any real conversion pair.
[[pair]]
target = \"nhllegacy-xbox360\"
source = \"synthsource-a\"
path = \"synthetic.pair-one\"
id_scheme = \"synthetic-scheme-1\"

[[pair]]
target = \"nhllegacy-xbox360\"
source = \"synthsource-b\"
path = \"synthetic.pair-two\"
id_scheme = \"synthetic-scheme-1\"

[[pair]]
target = \"nhl15-xbox360\"
source = \"synthsource-a\"
path = \"synthetic.pair-three\"
id_scheme = \"synthetic-scheme-2\"

[[pair]]
target = \"nhl21-ps4\"
source = \"synthsource-c\"
path = \"synthetic.pair-four\"
id_scheme = \"synthetic-scheme-2\"

[[pair]]
target = \"nhl21-ps4\"
source = \"synthsource-c\"
path = \"synthetic.pair-five\"
id_scheme = \"synthetic-scheme-3\"
";
    fs::write(&path, text).expect("write synthetic registry");
    path
}

/// A repository-shaped directory holding the three migration sources.
///
/// `game-qa-matrix.csv` is the **committed** one (self-contained, and the positional accounting
/// path it drives is meaningless against invented rows). The two asset matrices are synthetic and
/// carry a **deliberate, known disagreement**: `heads` exists only on the left, and `equipment`
/// disagrees on one column that both files declare.
fn synthetic_source_root(name: &str) -> PathBuf {
    let root = sandbox(name);
    let data = root.join("docs/audits/data");
    fs::create_dir_all(data.join("assets/nhllegacy/xbox360")).expect("data dirs");
    fs::copy(
        repo_root().join("docs/audits/data/game-qa-matrix.csv"),
        data.join("game-qa-matrix.csv"),
    )
    .expect("committed qa matrix");

    // Left source. `heads` is present here and nowhere else — the row-missing disagreement.
    fs::write(
        data.join("assets/nhllegacy/xbox360/capability.csv"),
        "asset_family,format,discover,identify,install,game_verified,evidence\n\
         portraits,synthetic-format,pass,pass,external,not_run,SYNTHETIC left-only note\n\
         equipment,synthetic-format,pass,partial,external,not_run,SYNTHETIC disagreeing row\n\
         heads,synthetic-format,pass,pass,not_run,not_run,SYNTHETIC destination-level heads row\n",
    )
    .expect("synthetic capability.csv");

    // Right source. Same two shared families; `identify` disagrees on `equipment`.
    fs::write(
        data.join("asset-capability-matrix.csv"),
        "game_id,platform,asset_family,discover,identify,install,game_verified,blocker\n\
         nhllegacy,xbox360,portraits,pass,pass,external,not_run,SYNTHETIC none\n\
         nhllegacy,xbox360,equipment,pass,pass,external,not_run,SYNTHETIC none\n",
    )
    .expect("synthetic asset-capability-matrix.csv");
    root
}

/// Freeze and migrate a synthetic source root through the **real** freeze/migrate path.
fn synthetic_frozen_and_migrated(name: &str) -> (PathBuf, PathBuf, migrate::MigrationReport) {
    let root = synthetic_source_root(&format!("{name}-sources"));
    let frozen = sandbox(&format!("{name}-frozen"));
    let candidate = sandbox(&format!("{name}-candidate"));
    migrate::freeze(&root, &frozen, "2026-09-07T00:00:00Z").expect("freeze");
    let layout = paths::Layout::new(&sandbox(&format!("{name}-evidence"))).expect("layout");
    let report = migrate::migrate(&frozen, &candidate, "mig-synthetic", &layout).expect("migrate");
    (frozen, candidate, report)
}

// ------------------------------------------------------------- A12, A27 -----

#[test]
fn a12_every_source_cell_is_accounted_for_exactly_once() {
    let (frozen, candidate, report) = frozen_and_migrated("a12");

    // Count the cells independently of the migration, straight from the frozen bytes.
    let mut counted = 0usize;
    for (name, _) in migrate::SOURCES {
        let text = fs::read_to_string(frozen.join(name)).expect("frozen source");
        let records = csv::parse(&text).expect("csv");
        for record in records.iter().skip(1) {
            counted += record.len();
        }
    }
    assert_eq!(
        report.source_cells, counted,
        "the migration must see every cell"
    );
    assert_eq!(
        report.accounting_rows, counted,
        "R-ACCOUNT: one row per cell, no more, no fewer"
    );

    // And the file really has that many rows.
    let accounting =
        fs::read_to_string(candidate.join("migration-accounting.csv")).expect("accounting");
    let rows = csv::parse(&accounting).expect("csv").len() - 1;
    assert_eq!(rows, counted);

    // Every blank cell is accounted for as evidence-free rather than dropped.
    assert!(accounting.contains("preserved-no-evidence"));
}

