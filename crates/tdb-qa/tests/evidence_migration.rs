/// **REAL-registry integration — an explicit, ignored-by-default coverage gap.**
///
/// This is the integration counterpart of the synthetic A11 case above, and the two are
/// **separately labelled on purpose**: A11 proves the *invariant* over a registry this file writes
/// and always runs; this case proves the invariant holds over the **live**
/// `defs/appearance/headmesh-matrix.toml`, and cannot run at HEAD because that registry is not
/// committed (C0-EVID-PROBE1 §4.1).
///
/// It is `#[ignore]`d rather than conditionally passing. A default `cargo test` therefore reports
/// it as **ignored — an unmet requirement that is visible in the run output** — and never as a
/// pass. Nothing here substitutes for it, and its being ignored is a coverage gap, not evidence
/// about any target.
///
/// Select it explicitly once the registry lands:
///
/// ```text
/// cargo test -p tdb-qa --test evidence_migration -- --ignored real_headmesh_registry
/// ```
///
/// When selected it **fails loudly** on an absent, unreadable or empty registry; it never reports
/// success for a registry it could not read or one that declares no pairs. It reads the registry
/// only — the destination-level claim it merges against is built from **sandbox** sources
/// (`synthetic_source_root`), so no hand-edited capability data is read, acquired or copied.
#[test]
#[ignore = "requires defs/appearance/headmesh-matrix.toml, which is NOT committed at HEAD \
            (C0-EVID-PROBE1 §4.1); this coverage is unmet until that registry lands — run with \
            `--ignored real_headmesh_registry` to execute it"]
fn real_headmesh_registry_integration_over_the_committed_registry() {
    let matrix = repo_root().join("defs/appearance/headmesh-matrix.toml");

    // 1. Absent or not a file — fail with the prerequisite named, not a silent pass.
    assert!(
        matrix.is_file(),
        "real-registry integration requires {}, which is absent or is not a file. It is not \
         committed at HEAD (C0-EVID-PROBE1 §4.1). Commit the registry, or leave this case ignored \
         — do NOT substitute the synthetic fixture from \
         `a11_pair_keys_stay_pair_specific_and_no_destination_claim_is_back_filled`, which proves \
         the invariant and not this registry.",
        matrix.display()
    );

    // 2. Unreadable or malformed — fail naming the file and the error.
    let keys = migrate::headmesh_pair_keys(&matrix, "game-acceptance").unwrap_or_else(|e| {
        panic!(
            "the committed registry {} could not be read as pair keys: {e}. A registry that does \
             not parse is a failure of this coverage, not an absence of it.",
            matrix.display()
        )
    });

    // 3. An empty registry is never success.
    assert!(
        !keys.is_empty(),
        "{} declared no `[[pair]]` entries, so this case proved nothing about pair identity. An \
         empty registry is a failure here, not coverage.",
        matrix.display()
    );

    // 4. Real pair identities are distinct and each carries a full conversion component.
    let distinct: std::collections::BTreeSet<String> =
        keys.iter().map(ToString::to_string).collect();
    assert_eq!(
        distinct.len(),
        keys.len(),
        "two committed pairs share one coverage key, so their evidence would merge: {:?}",
        keys.iter().map(ToString::to_string).collect::<Vec<_>>()
    );
    for key in &keys {
        assert!(
            key.conversion.is_some(),
            "committed pair {key} carries no conversion component (R-CONV)"
        );
    }
    let destinations: std::collections::BTreeSet<&str> =
        keys.iter().map(|k| k.target.as_str()).collect();
    // Recorded, not asserted against a fixed number: the registry's own shape is reported so a
    // reviewer can see it, and no count from any earlier document is re-imposed on it.
    println!(
        "real registry: {} pair(s) across {} destination(s)",
        keys.len(),
        destinations.len()
    );

    // 5. The documented migration → install → merge path, over sandbox sources only.
    let (_, candidate, _) = synthetic_frozen_and_migrated("real-headmesh");
    let root = sandbox("real-headmesh-root");
    approve_and_install(&candidate, &root);
    let legacy = store::load_legacy(&root).expect("legacy");
    let heads_claim = legacy
        .iter()
        .find(|c| c.claim_status_raw == "heads")
        .expect("the sandbox destination-level heads claim was migrated");
    assert!(!heads_claim.qualifies(), "R-LEGACY");

    // 6. That destination-level claim qualifies none of the REAL pair keys.
    let set = EvidenceSet {
        legacy,
        declared_universe: keys.iter().cloned().collect(),
        ..default_set()
    };
    let merged = merge::merge(&set);
    for key in &keys {
        let row = merged.row(&key.to_string()).expect("row");
        assert_eq!(row.automated, merge::AutomatedAxis::NotAttempted, "{key}");
        assert_eq!(row.manual, merge::ManualAxis::None, "{key}");
        assert_ne!(
            row.qualification,
            merge::Qualification::GameVerified,
            "{key}"
        );
        assert_ne!(
            row.qualification,
            merge::Qualification::AutomatedQualified,
            "{key}"
        );
    }
}

