fn write_approval(path: &Path, migration_id: &str, digest: &str, claims: usize) {
    let approval = Approval {
        schema: "qa-migration-approval/1".into(),
        migration_id: migration_id.into(),
        candidate_set_sha256: digest.into(),
        approved_by: "synthetic-example".into(),
        approved_utc: "2026-09-07T00:00:00Z".into(),
        accepted_records: 0,
        accepted_claims: claims,
    };
    fs::write(path, toml::to_string(&approval).expect("toml")).expect("write approval");
}

fn approve_and_install(candidate: &Path, root: &Path) -> migrate::InstallReport {
    let digest = migrate::candidate_digest(candidate).expect("digest");
    let approval_path = candidate.join("approval.toml");
    write_approval(&approval_path, "mig-c0-bulk1", &digest, 0);
    migrate::install(candidate, &approval_path, root, "mig-c0-bulk1").expect("install")
}

