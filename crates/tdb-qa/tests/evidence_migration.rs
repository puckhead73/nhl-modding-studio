static COUNTER: AtomicU32 = AtomicU32::new(0);

fn sandbox(name: &str) -> PathBuf {
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let dir = std::env::temp_dir()
        .join("tdb-qa-evidence-mig")
        .join(format!("{name}-{}-{n}", std::process::id()));
    fs::remove_dir_all(&dir).ok();
    fs::create_dir_all(&dir).expect("sandbox");
    dir
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// Freeze the three committed sources into an isolated directory and migrate them.
///
/// The committed sources are read-only inputs here and stay **self-contained**: they are committed
/// at HEAD, so a clean checkout has them. Cases that need a *known* disagreement or a registry that
/// HEAD does not carry use [`synthetic_source_root`] instead — see the module note in
/// `docs/receipts/c0-evid-repair1.md`.
fn frozen_and_migrated(name: &str) -> (PathBuf, PathBuf, migrate::MigrationReport) {
    let frozen = sandbox(&format!("{name}-frozen"));
    let candidate = sandbox(&format!("{name}-candidate"));
    migrate::freeze(&repo_root(), &frozen, "2026-09-07T00:00:00Z").expect("freeze");
    let layout = paths::Layout::new(&sandbox("mig-evidence")).expect("layout");
    let report = migrate::migrate(&frozen, &candidate, "mig-c0-bulk1", &layout).expect("migrate");
    (frozen, candidate, report)
}

