"""Build defs/schedules/stock-partitions.json from research R113b (receipt 48; R123 Q9 / Q10, accepted 28 Sep 2026
for single-phase generation).

Keeps only complete single-phase stock partitions: model `stock_partition`, stock validation `conforms`, all five
controls detected, every group a complete clique, and not the PS4 18-21 `austrianschedule` (a tagged two-phase
table, R123 Q10: withheld). Studio offers a table's groups only when the open file's SHA-256, the table and the
R113 mapping fingerprint all equal a row here. Read-only on the research file; standard library only.

    python tools/schedule/extract_r113_stock_partitions.py [--check]
"""
import hashlib
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(REPO, "docs", "research", "overnight-2026-09-26", "data", "r113b-stock-partition-import-table.json")
OUT = os.path.join(REPO, "defs", "schedules", "stock-partitions.json")
TWO_PHASE = {"austrianschedule"}


def build():
    raw = open(SRC, "rb").read()
    d = json.loads(raw)
    rows = []
    for c in d["contracts"]:
        if c["model"] != "stock_partition" or c["stock_validation"] != "conforms" or not c["controls_all_detected"] or not c["clique_complete_all"]:
            continue
        if c["table"] in TWO_PHASE:
            continue
        rows.append({k: c[k] for k in ("source", "aliases", "db_sha256", "table", "league_id", "quotas", "n_members", "games",
                                        "groups_by_index", "groups_by_abbr", "mapping_fingerprint")})
    rows.sort(key=lambda r: (r["source"], r["table"]))
    return {
        "about": "Single-phase stock partitions (research R113 / R113b, consumed under R123 Q9). A row applies only to the exact "
                 "database SHA-256, table and mapping fingerprint it names (SHA-256 of the canonical JSON [[rank, index, artabbr], ...]). "
                 "Two-phase (austrianschedule) and irregular tables are not listed. Generated by tools/schedule/extract_r113_stock_partitions.py.",
        "from": "docs/research/overnight-2026-09-26/data/r113b-stock-partition-import-table.json",
        "from_sha256": hashlib.sha256(raw).hexdigest(),
        "contracts": rows,
    }


def main():
    out = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        same = os.path.isfile(OUT) and open(OUT, encoding="utf-8").read() == out
        print("identical" if same else "DIFFERENT")
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"{len(json.loads(out)['contracts'])} contracts -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
