"""Preview GLB writer for a candidate exchange (`native-fit-exchange/1`): a self-contained glTF 2.0 binary the
application viewport can load without importing any conversion code. numpy + stdlib only; no Blender.

Frame: the native exchange frame (metres, +Y up, +Z forward, +X = character left) is the glTF frame (+Y up, +Z
faces the viewer, right-handed), so positions are written as-is (identity). Native UV (origin top-left, v down) is
also glTF's TEXCOORD convention, so per-record UVs are written as-is and the baked atlas PNG is embedded unchanged.
Records in the exchange are already per-(vertex, uv) splits, so per-corner UVs survive one-to-one.

Materials are PREVIEW APPROXIMATIONS and are declared as such in node/material extras and in the returned info:
- head: metallic-roughness PBR, base colour = baked atlas, roughness 0.85, metallic 0 (the game shader, normal map and
  hair are not reproduced);
- eyes: flat light material (native eye texture/shader is not available to the worker; their UVs tile a texture
  the exchange does not carry);
- cards/haircap: flat dark materials, untouched native geometry, default hidden (their textures are not carried).
Normals are recomputed from the candidate geometry (area-weighted, merged over coincident records) because native
normals in the exchange are reference data for the donor, regenerated by the packer for the fitted head.
"""
import json, struct
from pathlib import Path
import numpy as np
from . import exchange as X

PREVIEW_SCHEMA = 'nhl-head-preview/1'
NODE_POLICY = {   # submesh name -> (role, default_visible, material approximation)
    X.HEAD: ('head', True, 'pbr_metallic_roughness base colour = baked atlas (roughness 0.85, metallic 0); game shader/normal map not reproduced'),
    X.EYES: ('eyes', True, 'flat light material [0.92,0.92,0.92]; native eye texture/shader not available to the worker'),
    'geo_cardsBShape': ('hair_cards', False, 'flat dark material, untouched native geometry; hair texture not carried; visibility in game unresolved'),
    'geo_haircapShape': ('haircap', False, 'flat dark material, untouched native geometry; texture not carried'),
}
FLAT_COLOURS = {'eyes': [0.92, 0.92, 0.92, 1.0], 'hair_cards': [0.16, 0.12, 0.10, 1.0], 'haircap': [0.22, 0.17, 0.14, 1.0], 'other': [0.6, 0.6, 0.6, 1.0]}


def _merged_normals(P, T):
    """Area-weighted vertex normals with coincident records merged (seams stay smooth)."""
    P = np.asarray(P, float); T = np.asarray(T)
    fn = np.cross(P[T[:, 1]] - P[T[:, 0]], P[T[:, 2]] - P[T[:, 0]])
    vn = np.zeros_like(P)
    for k in range(3): np.add.at(vn, T[:, k], fn)
    keys = {}
    for i, p in enumerate(np.round(P, 7)):
        keys.setdefault(p.tobytes(), []).append(i)
    for ids in keys.values():
        if len(ids) > 1: vn[ids] = vn[ids].sum(0)
    n = np.linalg.norm(vn, axis=1); bad = n < 1e-20; vn[bad] = [0, 0, 1]; n[bad] = 1
    return vn / n[:, None]


def _pad4(b, fill=b'\x00'):
    return b + fill * ((4 - len(b) % 4) % 4)


class _Buffer:
    def __init__(self): self.chunks = []; self.views = []; self.offset = 0

    def add(self, data, target=None):
        data = bytes(data); padded = _pad4(data); self.views.append({'buffer': 0, 'byteOffset': self.offset, 'byteLength': len(data), **({'target': target} if target else {})})
        self.chunks.append(padded); self.offset += len(padded); return len(self.views) - 1


def build_glb(ex, atlas_png, job_id, candidate_status, include=None, extras=None):
    """Return (glb_bytes, info). `include` limits the submeshes (default: all in NODE_POLICY order then others)."""
    atlas = Path(atlas_png).read_bytes()
    buf = _Buffer(); accessors = []; meshes = []; nodes = []; materials = []; info_nodes = []
    img_view = buf.add(atlas)
    images = [{'name': 'atlas_1024', 'mimeType': 'image/png', 'bufferView': img_view}]
    samplers = [{'magFilter': 9729, 'minFilter': 9987, 'wrapS': 10497, 'wrapT': 10497}]
    textures = [{'sampler': 0, 'source': 0}]

    def accessor(arr, ctype, atype, target, minmax=False):
        arr = np.ascontiguousarray(arr); v = buf.add(arr.tobytes(), target)
        a = {'bufferView': v, 'componentType': ctype, 'count': int(arr.shape[0]), 'type': atype}
        if minmax: a['min'] = [float(x) for x in arr.min(0)]; a['max'] = [float(x) for x in arr.max(0)]
        accessors.append(a); return len(accessors) - 1

    def material(role, name):
        if role == 'head': m = {'name': name, 'pbrMetallicRoughness': {'baseColorTexture': {'index': 0, 'texCoord': 0}, 'metallicFactor': 0.0, 'roughnessFactor': 0.85}, 'doubleSided': False}
        else: m = {'name': name, 'pbrMetallicRoughness': {'baseColorFactor': FLAT_COLOURS.get(role, FLAT_COLOURS['other']), 'metallicFactor': 0.0, 'roughnessFactor': 0.35 if role == 'eyes' else 0.9}, 'doubleSided': role in ('hair_cards',)}
        m['extras'] = {'preview_approximation': NODE_POLICY.get(name, ('other', False, 'flat material; untouched native submesh'))[2]}
        materials.append(m); return len(materials) - 1

    names = [m['name'] for m in ex['submeshes']]
    order = [n for n in NODE_POLICY if n in names] + [n for n in names if n not in NODE_POLICY]
    for name in order:
        if include is not None and name not in include: continue
        m = X.submesh(ex, name); role, vis, approx = NODE_POLICY.get(name, ('other', False, 'flat material; untouched native submesh'))
        P = np.asarray(m['positions'], np.float32); T = np.asarray(m['triangles'], np.int64); U = np.asarray(m['uv'], np.float32)
        N = _merged_normals(P.astype(float), T).astype(np.float32)
        idx = T.reshape(-1); itype, ctype = (np.uint16, 5123) if len(P) < 65536 else (np.uint32, 5125)
        attrs = {'POSITION': accessor(P, 5126, 'VEC3', 34962, True), 'NORMAL': accessor(N, 5126, 'VEC3', 34962), 'TEXCOORD_0': accessor(U, 5126, 'VEC2', 34962)}
        ind = accessor(idx.astype(itype), ctype, 'SCALAR', 34963)
        mat = material(role, name)
        fitted = bool(m['positions'] != m['original_positions'])
        node_extras = {'role': role, 'submesh': name, 'native_role': m.get('role'), 'records': int(len(P)), 'triangles': int(len(T)), 'positions_changed_vs_donor': fitted, 'default_visible': vis, 'material_approximation': approx, 'normals': 'recomputed from candidate geometry (merged coincident records)'}
        meshes.append({'name': name, 'primitives': [{'attributes': attrs, 'indices': ind, 'material': mat, 'mode': 4}], 'extras': node_extras})
        nodes.append({'name': name, 'mesh': len(meshes) - 1, 'extras': node_extras})
        info_nodes.append({'name': name, **node_extras})
    asset_extras = {'schema': PREVIEW_SCHEMA, 'job_id': job_id, 'candidate_status': candidate_status, 'diagnostic_only': candidate_status != 'ready_for_experimental_packing',
                    'frame': 'native exchange frame == glTF frame (metres, +Y up, +Z forward/viewer, +X character left); positions written unchanged', 'uv': 'native per-record UV == glTF TEXCOORD_0 (origin top-left); atlas PNG embedded unchanged',
                    'approximations': sorted({n['material_approximation'] for n in info_nodes} | {'normals recomputed from candidate geometry; native shading is regenerated by the packer', 'no rig, no morphs, rest pose only'}), **(extras or {})}
    gltf = {'asset': {'version': '2.0', 'generator': 'nhl-head-mesh-converter src/conversion/preview.py', 'extras': asset_extras}, 'scene': 0, 'scenes': [{'name': 'candidate', 'nodes': list(range(len(nodes)))}],
            'nodes': nodes, 'meshes': meshes, 'materials': materials, 'textures': textures, 'images': images, 'samplers': samplers, 'accessors': accessors, 'bufferViews': buf.views, 'buffers': [{'byteLength': buf.offset}]}
    js = _pad4(json.dumps(gltf, separators=(',', ':'), sort_keys=True).encode('utf-8'), b' '); bin_ = b''.join(buf.chunks)
    total = 12 + 8 + len(js) + 8 + len(bin_)
    glb = struct.pack('<III', 0x46546C67, 2, total) + struct.pack('<II', len(js), 0x4E4F534A) + js + struct.pack('<II', len(bin_), 0x004E4942) + bin_
    info = {'schema': PREVIEW_SCHEMA, 'bytes': total, 'nodes': info_nodes, 'atlas_embedded_bytes': len(atlas), 'approximations': asset_extras['approximations'], 'frame': asset_extras['frame'], 'uv': asset_extras['uv'], 'diagnostic_only': asset_extras['diagnostic_only']}
    return glb, info


def write_glb(ex, atlas_png, out_path, job_id, candidate_status, **kw):
    out = Path(out_path)
    if out.exists(): raise FileExistsError(f'refusing to overwrite {out}')
    glb, info = build_glb(ex, atlas_png, job_id, candidate_status, **kw); out.write_bytes(glb); info['path'] = str(out); return info


def read_glb(path):
    """Minimal GLB reader for verification: returns (gltf dict, {node name: {'positions','normals','uv','indices'}}, image bytes)."""
    b = Path(path).read_bytes(); magic, ver, total = struct.unpack_from('<III', b, 0)
    if magic != 0x46546C67 or ver != 2 or total != len(b): raise ValueError('not a GLB v2 file or truncated')
    jl, jt = struct.unpack_from('<II', b, 12); js = b[20:20 + jl]; bl, bt = struct.unpack_from('<II', b, 20 + jl); bin_ = b[28 + jl:28 + jl + bl]
    if jt != 0x4E4F534A or bt != 0x004E4942 or bl + jl + 28 != total: raise ValueError('GLB chunk layout invalid')
    g = json.loads(js.decode('utf-8'))
    dt = {5126: np.float32, 5123: np.uint16, 5125: np.uint32}; nc = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3}

    def acc(i):
        a = g['accessors'][i]; v = g['bufferViews'][a['bufferView']]; raw = bin_[v['byteOffset']:v['byteOffset'] + v['byteLength']]
        return np.frombuffer(raw, dt[a['componentType']], count=a['count'] * nc[a['type']]).reshape(a['count'], nc[a['type']])
    out = {}
    for n in g['nodes']:
        pr = g['meshes'][n['mesh']]['primitives'][0]; at = pr['attributes']
        out[n['name']] = {'positions': acc(at['POSITION']), 'normals': acc(at['NORMAL']), 'uv': acc(at['TEXCOORD_0']), 'indices': acc(pr['indices']).reshape(-1, 3), 'material': g['materials'][pr['material']], 'extras': n.get('extras', {})}
    img = None
    if g.get('images'):
        v = g['bufferViews'][g['images'][0]['bufferView']]; img = bin_[v['byteOffset']:v['byteOffset'] + v['byteLength']]
    return g, out, img


def verify_glb(path, ex, atlas_png):
    """Check a preview against its exchange and atlas: positions/UV/indices exact per node, image bytes identical."""
    g, nodes, img = read_glb(path); problems = []
    if img != Path(atlas_png).read_bytes(): problems.append('embedded atlas differs from atlas PNG')
    for name, nd in nodes.items():
        m = X.submesh(ex, name)
        if not np.array_equal(nd['positions'], np.asarray(m['positions'], np.float32)): problems.append(f'{name}: positions differ')
        if not np.array_equal(nd['uv'], np.asarray(m['uv'], np.float32)): problems.append(f'{name}: uv differ')
        if not np.array_equal(nd['indices'].astype(np.int64), np.asarray(m['triangles'], np.int64)): problems.append(f'{name}: triangles differ')
        if not np.isfinite(nd['normals']).all() or np.abs(np.linalg.norm(nd['normals'], axis=1) - 1).max() > 1e-3: problems.append(f'{name}: normals not unit')
    if g['asset'].get('extras', {}).get('schema') != PREVIEW_SCHEMA: problems.append('asset.extras.schema missing')
    return (not problems), problems, {'nodes': list(nodes)}
